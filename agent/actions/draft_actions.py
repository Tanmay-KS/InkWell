"""Draft action generation.

Phase 1 — Person B.

Turns a deadline into something the user can act on. The plan's first
draft actions are a cancellation email and a refund request.

Two rules shape this module:

* **A draft, not an action.** Ledger never sends anything. It produces
  text the user reads, edits, and sends. This is not only a safety
  property — it is what makes the agent trustworthy enough to hold a
  household's renewal dates.
* **Personal details are placeholders in the draft, not the real thing.**
  A draft written in the user's own voice contains their policy number,
  their address, their account. That draft is generated inside the
  sandbox, and the version that leaves is the redacted one — the personal
  details are substituted back in only at the moment of display, in the
  user's own channel, which is inside the sandbox boundary.

  This is the subtle part of the whole project: the agent genuinely needs
  the real values to write a useful draft, and yet the values must not
  travel. See `docs/architecture.md`.

The bodies are written as templates rather than generated by a model.
A cancellation email has a fixed shape — who, what, which reference, what
date, what ask — and a template gets all five right every time, costs
nothing, has no egress, and cannot hallucinate an account number. The
model path is available for a message that is not one of the known
shapes.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import date
from enum import StrEnum

from agent.deadlines.flag_deadlines import Deadline, DeadlineKind
from agent.memory.hermes_memory import HouseholdItem


class ActionKind(StrEnum):
    """The kinds of action Ledger knows how to draft."""

    CANCEL = "cancel"
    REFUND = "refund"
    RENEW = "renew"
    REMIND = "remind"
    CONTACT = "contact"
    DISPUTE = "dispute"


@dataclass(slots=True)
class DraftAction:
    """A drafted action for the user to review and send.

    Attributes:
        kind: What kind of action this is.
        subject: The household item it concerns.
        title: A short label for the UI.
        body: The draft text, with personal details still in place — it is
            generated and consumed inside the sandbox.
        channel: Where it would be sent, if sent.
        recipient: Who it would go to.
        personal_details: The values referenced in the body, so that the
            redaction step knows what to mask before the draft is shown
            outside the boundary.
        metadata: Everything else.
    """

    kind: ActionKind
    subject: str | None
    title: str
    body: str
    channel: str | None = None
    recipient: str | None = None
    personal_details: list[str] = field(default_factory=list)
    metadata: dict[str, object] = field(default_factory=dict)

    def redacted_body(self) -> str:
        """The body with the personal details masked.

        This is the version that may leave the sandbox. The real one is
        for the user's own channel, which is inside the boundary.
        """
        from privacy_router.redact import local_redact

        return local_redact(self.body, names=self.personal_details).text


# --- templates --------------------------------------------------------------


def _kind_label(item: HouseholdItem | None) -> str:
    """What to call the thing in a letter to the company."""
    if item is None:
        return "policy"
    kind = (item.kind or "").strip().lower()
    return {
        "insurance": "insurance policy",
        "membership": "membership",
        "subscription": "subscription",
        "licence": "licence",
        "medical": "coverage plan",
    }.get(kind, kind or "policy")


def _reference_line(item: HouseholdItem | None) -> str:
    if item is None or not item.reference:
        return ""
    label = "Policy number" if (item.kind == "insurance") else "Account number"
    return f"{label}: {item.reference}\n\n"


def _cancellation(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)
    when = deadline.date.strftime("%d %B %Y")

    body = f"""Dear {provider},

I am writing to cancel my {kind}. Please close the account and stop any further billing.

{_reference_line(item)}The notice I received gives {when} as the renewal date, and I would like the cancellation to take effect before then so that I am not charged for another period.

Please confirm the cancellation in writing, and let me know if there is anything else you need from me to process it.

Kind regards,
{item.holder if item else ""}"""

    title = f"Cancel {kind} with {provider}"
    return title, body


def _refund(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)
    amount = f" of {item.amount:.2f}" if item and item.amount is not None else ""
    when = deadline.date.strftime("%d %B %Y")

    body = f"""Dear {provider},

I am writing to request a refund{amount} for my {kind}.

{_reference_line(item)}I would like to know why this charge was taken and, if it was not authorised, to have it refunded to the original payment method. The renewal date on my notice is {when}.

Please let me know what you need from me to process the refund, and how long it will take.

Kind regards,
{item.holder if item else ""}"""

    title = f"Request a refund from {provider}"
    return title, body


def _renewal(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)
    when = deadline.date.strftime("%d %B %Y")

    body = f"""Dear {provider},

I am writing to renew my {kind} for the next period.

{_reference_line(item)}The renewal date on my notice is {when}. Please confirm the renewal and let me know the amount due and when payment will be taken.

Kind regards,
{item.holder if item else ""}"""

    title = f"Renew {kind} with {provider}"
    return title, body


def _reminder(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)
    when = deadline.date.strftime("%d %B %Y")

    body = f"""Reminder: {kind} from {provider} renews on {when}.

{_reference_line(item)}This is a draft — review it and send it yourself if you want to act on it."""

    title = f"{kind.capitalize()} from {provider} renews {when}"
    return title, body


def _contact(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)

    body = f"""Dear {provider},

I am writing about my {kind}. My notice gives {deadline.date.strftime("%d %B %Y")} as the date I need to act by.

{_reference_line(item)}Could you confirm what I need to do, and what it will cost?

Kind regards,
{item.holder if item else ""}"""

    title = f"Contact {provider} about {kind}"
    return title, body


def _dispute(item: HouseholdItem | None, deadline: Deadline) -> tuple[str, str]:
    provider = item.provider if item else deadline.title
    kind = _kind_label(item)

    body = f"""Dear {provider},

I am writing to dispute a charge on my {kind}.

{_reference_line(item)}The date on my notice is {deadline.date.strftime("%d %B %Y")}. I have not authorised the charge in question. Please investigate, and confirm the outcome in writing.

Kind regards,
{item.holder if item else ""}"""

    title = f"Dispute a charge from {provider}"
    return title, body


_TEMPLATES = {
    ActionKind.CANCEL: _cancellation,
    ActionKind.REFUND: _refund,
    ActionKind.RENEW: _renewal,
    ActionKind.REMIND: _reminder,
    ActionKind.CONTACT: _contact,
    ActionKind.DISPUTE: _dispute,
}


def _action_kind_for(deadline: Deadline) -> ActionKind:
    """Which kind of action a deadline calls for.

    A cancellation window is a cancel. A payment that is due is a
    renewal. Anything else is a reminder — the generic, useful thing.
    """
    if deadline.kind is DeadlineKind.CANCELLATION_WINDOW:
        return ActionKind.CANCEL
    if deadline.kind is DeadlineKind.PAYMENT_DUE:
        return ActionKind.RENEW
    if deadline.kind is DeadlineKind.RENEWAL:
        return ActionKind.RENEW
    return ActionKind.REMIND


def draft_action(
    deadline: object,
    *,
    context: object | None = None,
    model: str | None = None,
    kind: ActionKind | None = None,
) -> DraftAction:
    """Draft an action for a deadline.

    Args:
        deadline: The `Deadline` to act on.
        context: The household item and any prior related correspondence.
        model: Defaults to `LEDGER_MODEL_SUPER`. Unused on the template
            path, which is the primary one.
        kind: Force a kind of action. By default it is inferred from the
            deadline's kind.

    Returns:
        A `DraftAction`. The body is written to be sent as-is by a human:
        no placeholders like [YOUR_NAME], no meta-commentary about being
        an AI, and a specific ask with a date attached.
    """
    if not isinstance(deadline, Deadline):
        raise TypeError("draft_action needs a Deadline")

    item = context if isinstance(context, HouseholdItem) else None
    action_kind = kind or _action_kind_for(deadline)

    title, body = _TEMPLATES[action_kind](item, deadline)

    personal_details = []
    if item is not None:
        for value in (item.reference, item.holder):
            if value:
                personal_details.append(value)

    return DraftAction(
        kind=action_kind,
        subject=item.item_id if item else deadline.subject,
        title=title,
        body=body.strip(),
        recipient=item.provider if item else None,
        personal_details=personal_details,
        metadata={
            "deadline_kind": deadline.kind.value,
            "deadline_date": deadline.date.isoformat(),
            "evidence": deadline.evidence,
            "today": date.today().isoformat(),
        },
    )
